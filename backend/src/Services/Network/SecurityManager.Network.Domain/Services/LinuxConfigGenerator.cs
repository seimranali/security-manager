using System.Text;
using SecurityManager.Network.Domain.Entities;
using SecurityManager.Network.Domain.Enums;
using SecurityManager.Shared.Kernel.Networking;

namespace SecurityManager.Network.Domain.Services;

public sealed record GeneratedFile(string Path, string Language, string Description, string Content);

/// <summary>
/// Renders a gateway's configuration for a standard Linux gateway stack:
/// iproute2 (interfaces, routes, policy routing), nftables (NAT), WireGuard, strongSwan (swanctl) and keepalived (VRRP).
/// Secrets (WireGuard private keys, IPsec pre-shared keys) are never emitted; configs reference them on the device.
/// </summary>
public static class LinuxConfigGenerator
{
    public static IReadOnlyList<GeneratedFile> Generate(Gateway g, HaCluster? cluster = null, IReadOnlyList<Gateway>? clusterMembers = null)
    {
        var files = new List<GeneratedFile>
        {
            new("network/apply-network.sh", "bash", "Interfaces, addresses, static routes and policy routing (iproute2). Idempotent.", Network(g)),
            new("nftables/sm-nat.nft", "nft", "NAT: masquerade, source NAT, port forwards and 1:1 NAT (nftables).", Nat(g)),
        };

        foreach (var t in g.Tunnels.Where(t => t.Type == VpnType.WireGuard).OrderBy(t => t.InterfaceName))
            files.Add(new($"wireguard/{t.InterfaceName}.conf", "ini", $"WireGuard tunnel '{t.Name}' (wg-quick).", WireGuard(t)));

        var ipsec = g.Tunnels.Where(t => t.Type == VpnType.IpsecSiteToSite).OrderBy(t => t.Name).ToList();
        if (ipsec.Count > 0)
            files.Add(new("strongswan/swanctl.d/security-manager.conf", "conf", "IPsec site-to-site tunnels (strongSwan swanctl).", Ipsec(ipsec)));

        if (cluster is not null && cluster.VirtualIps.Count > 0)
            files.Add(new("keepalived/keepalived.conf", "conf", $"High availability for cluster '{cluster.Name}' (keepalived / VRRP).",
                Keepalived(g, cluster, clusterMembers ?? [g])));

        files.Add(new("README.txt", "text", "How to apply this configuration.", Readme(g, files)));
        return files;
    }

    private static string Header(Gateway g, string comment = "#") =>
        $"{comment} Generated by Security Manager for {g.Hostname} ({g.Name}), revision {g.ConfigRevision}.\n{comment} Do not edit by hand: changes are overwritten on the next export.\n";

    private static string Disabled(bool enabled) => enabled ? "" : "# [disabled] ";

    // ---------------------------------------------------------------- iproute2
    private static string Network(Gateway g)
    {
        var sb = new StringBuilder("#!/usr/bin/env bash\n").Append(Header(g)).AppendLine("set -euo pipefail").AppendLine();

        var interfaces = g.Interfaces.ToList();
        var anyV6 = interfaces.Any(i => i.AddressCidr is { IsIPv4: false });
        sb.AppendLine("# Enable packet forwarding (this host routes traffic).")
          .AppendLine("sysctl -qw net.ipv4.ip_forward=1");
        if (anyV6) sb.AppendLine("sysctl -qw net.ipv6.conf.all.forwarding=1");
        sb.AppendLine();

        // Create virtual devices first: bonds and bridges, then VLANs (which may sit on bonds).
        var order = interfaces.OrderBy(i => i.Type switch
        {
            InterfaceType.Physical or InterfaceType.Loopback => 0,
            InterfaceType.Bond => 1,
            InterfaceType.Bridge => 2,
            _ => 3
        }).ThenBy(i => i.Name).ToList();

        sb.AppendLine("# ---- Interfaces ----");
        foreach (var i in order)
        {
            var p = Disabled(i.IsEnabled);
            sb.AppendLine($"# {i.Name}: {i.Type}, zone {i.Zone}{(i.Description is null ? "" : $" — {i.Description}")}");
            switch (i.Type)
            {
                case InterfaceType.Bond:
                    sb.AppendLine($"{p}ip link show {i.Name} >/dev/null 2>&1 || ip link add {i.Name} type bond mode active-backup miimon 100");
                    foreach (var m in NetworkNames.SplitList(i.Members))
                        sb.AppendLine($"{p}ip link set {m} down && ip link set {m} master {i.Name}");
                    break;
                case InterfaceType.Bridge:
                    sb.AppendLine($"{p}ip link show {i.Name} >/dev/null 2>&1 || ip link add {i.Name} type bridge");
                    foreach (var m in NetworkNames.SplitList(i.Members))
                        sb.AppendLine($"{p}ip link set {m} master {i.Name} && ip link set {m} up");
                    break;
                case InterfaceType.Vlan:
                    sb.AppendLine($"{p}ip link show {i.Name} >/dev/null 2>&1 || ip link add link {i.Parent} name {i.Name} type vlan id {i.VlanId}");
                    break;
            }
            if (i.Mtu is { } mtu) sb.AppendLine($"{p}ip link set dev {i.Name} mtu {mtu}");
            sb.AppendLine($"{p}ip link set dev {i.Name} {(i.IsEnabled ? "up" : "down")}");
            switch (i.Mode)
            {
                case AddressingMode.Static:
                    sb.AppendLine($"{p}ip addr replace {i.Address} dev {i.Name}");
                    break;
                case AddressingMode.Dhcp:
                    sb.AppendLine($"{p}# Address via DHCP: managed by systemd-networkd/dhclient for {i.Name}");
                    break;
            }
            sb.AppendLine();
        }

        sb.AppendLine("# ---- Static routes ----");
        foreach (var r in g.Routes.OrderBy(r => r.Table).ThenBy(r => r.Metric).ThenBy(r => r.Destination))
        {
            if (r.Description is not null) sb.AppendLine($"# {r.Description}");
            var dest = Cidr.TryParse(r.Destination, out var c) ? (c.Prefix == 0 ? "default" : c.NetworkText) : r.Destination;
            var family = Cidr.TryParse(r.Destination, out c) && !c.IsIPv4 ? "-6 " : "";
            var via = string.IsNullOrWhiteSpace(r.NextHop) ? "" : $" via {r.NextHop}";
            var dev = string.IsNullOrWhiteSpace(r.Interface) ? "" : $" dev {r.Interface}";
            var table = r.Table == NetworkNames.MainTable ? "" : $" table {r.Table}";
            sb.AppendLine($"{Disabled(r.IsEnabled)}ip {family}route replace {dest}{via}{dev} metric {r.Metric}{table}");
        }
        sb.AppendLine();

        sb.AppendLine("# ---- Policy routing (dedicated gateways) ----");
        foreach (var p in g.Policies.OrderBy(p => p.Priority))
        {
            if (p.Description is not null) sb.AppendLine($"# {p.Description}");
            var parts = new List<string>();
            if (!string.IsNullOrWhiteSpace(p.Source)) parts.Add($"from {p.Source}");
            if (!string.IsNullOrWhiteSpace(p.Destination)) parts.Add($"to {p.Destination}");
            if (!string.IsNullOrWhiteSpace(p.InInterface)) parts.Add($"iif {p.InInterface}");
            var table = p.Table == NetworkNames.MainTable ? "main" : p.Table.ToString();
            var pre = Disabled(p.IsEnabled);
            sb.AppendLine($"{pre}ip rule del priority {p.Priority} 2>/dev/null || true");
            sb.AppendLine($"{pre}ip rule add priority {p.Priority} {string.Join(' ', parts)} lookup {table}");
        }
        sb.AppendLine().AppendLine("ip route flush cache");
        return sb.ToString();
    }

    // ---------------------------------------------------------------- nftables NAT
    private static string Nat(Gateway g)
    {
        var sb = new StringBuilder("#!/usr/sbin/nft -f\n").Append(Header(g))
            .AppendLine("# Only NAT is managed here; packet filtering policy comes from the Firewall service.")
            .AppendLine("# Re-applying replaces the table atomically.")
            .AppendLine("table ip sm_nat")
            .AppendLine("delete table ip sm_nat")
            .AppendLine().AppendLine("table ip sm_nat {");

        var rules = g.NatRules.OrderBy(n => n.Priority).ThenBy(n => n.Name).ToList();

        sb.AppendLine("    chain prerouting {")
          .AppendLine("        type nat hook prerouting priority dstnat; policy accept;");
        foreach (var n in rules.Where(n => n.Type is NatType.PortForward or NatType.OneToOne))
            sb.AppendLine($"        {Disabled(n.IsEnabled)}{Prerouting(n)}");
        sb.AppendLine("    }").AppendLine();

        sb.AppendLine("    chain postrouting {")
          .AppendLine("        type nat hook postrouting priority srcnat; policy accept;");
        foreach (var n in rules.Where(n => n.Type is NatType.Masquerade or NatType.SourceNat or NatType.OneToOne))
            sb.AppendLine($"        {Disabled(n.IsEnabled)}{Postrouting(n)}");
        sb.AppendLine("    }").AppendLine("}");
        return sb.ToString();
    }

    private static string Match(NatRule n, bool includeDestination = true)
    {
        var parts = new List<string>();
        if (!string.IsNullOrWhiteSpace(n.InInterface) && n.Type is NatType.PortForward or NatType.OneToOne) parts.Add($"iifname \"{n.InInterface}\"");
        if (!string.IsNullOrWhiteSpace(n.OutInterface) && n.Type is NatType.Masquerade or NatType.SourceNat) parts.Add($"oifname \"{n.OutInterface}\"");
        if (!string.IsNullOrWhiteSpace(n.Source)) parts.Add($"ip saddr {n.Source}");
        if (includeDestination && !string.IsNullOrWhiteSpace(n.Destination)) parts.Add($"ip daddr {n.Destination}");
        if (n.UsesPorts) parts.Add($"{n.Protocol.ToString().ToLowerInvariant()} dport {n.DestinationPort!.Trim()}");
        else if (n.Protocol != NatProtocol.Any) parts.Add($"meta l4proto {n.Protocol.ToString().ToLowerInvariant()}");
        return string.Join(' ', parts);
    }

    private static string Comment(NatRule n) => $"comment \"{n.Name.Replace("\"", "'")}\"";

    private static string Prerouting(NatRule n) => n.Type == NatType.OneToOne
        ? $"ip daddr {n.Destination} dnat to {n.TranslatedAddress} {Comment(n)}"
        : $"{Match(n)} dnat to {n.TranslatedAddress}{(n.TranslatedPort is { } port ? $":{port}" : "")} {Comment(n)}";

    private static string Postrouting(NatRule n) => n.Type switch
    {
        NatType.Masquerade => $"{Match(n)} masquerade {Comment(n)}",
        NatType.SourceNat => $"{Match(n)} snat to {n.TranslatedAddress} {Comment(n)}",
        _ => $"ip saddr {n.TranslatedAddress} snat to {n.Destination} {Comment(n)}" // one-to-one return path
    };

    // ---------------------------------------------------------------- WireGuard
    private static string WireGuard(VpnTunnel t)
    {
        var sb = new StringBuilder()
            .AppendLine($"# WireGuard tunnel '{t.Name}'{(t.Description is null ? "" : $" — {t.Description}")}")
            .AppendLine("# The private key is never stored by Security Manager. Create it once on the gateway:")
            .AppendLine($"#   umask 077; wg genkey | tee /etc/wireguard/{t.InterfaceName}.key | wg pubkey > /etc/wireguard/{t.InterfaceName}.pub")
            .AppendLine(t.PublicKey is null ? "# Then record the public key in Security Manager." : $"# Expected public key: {t.PublicKey}")
            .AppendLine(t.IsEnabled ? "" : "# [disabled] This tunnel is disabled; do not start it.\n")
            .AppendLine("[Interface]")
            .AppendLine($"Address = {t.TunnelAddress}")
            .AppendLine($"ListenPort = {t.ListenPort}");
        if (t.Mtu is { } mtu) sb.AppendLine($"MTU = {mtu}");
        sb.AppendLine("PostUp = wg set %i private-key /etc/wireguard/%i.key");

        foreach (var p in t.Peers.OrderBy(p => p.Name))
        {
            var pre = p.IsEnabled ? "" : "# ";
            sb.AppendLine().AppendLine($"# Peer: {p.Name}{(p.IsEnabled ? "" : " [disabled]")}")
              .AppendLine($"{pre}[Peer]")
              .AppendLine($"{pre}PublicKey = {p.PublicKey}")
              .AppendLine($"{pre}AllowedIPs = {string.Join(", ", NetworkNames.SplitList(p.AllowedIps))}");
            if (!string.IsNullOrWhiteSpace(p.Endpoint)) sb.AppendLine($"{pre}Endpoint = {p.Endpoint}");
            if (p.PersistentKeepalive > 0) sb.AppendLine($"{pre}PersistentKeepalive = {p.PersistentKeepalive}");
        }
        return sb.ToString();
    }

    // ---------------------------------------------------------------- strongSwan
    private static string Ipsec(IReadOnlyList<VpnTunnel> tunnels)
    {
        var sb = new StringBuilder("# IPsec site-to-site tunnels (strongSwan swanctl).\n")
            .AppendLine("# Pre-shared keys are never stored by Security Manager. Put them in")
            .AppendLine("# /etc/swanctl/conf.d/secrets.conf (root-only), one ike-<name> block per tunnel.")
            .AppendLine().AppendLine("connections {");
        foreach (var t in tunnels)
        {
            var pre = t.IsEnabled ? "" : "# ";
            var locals = string.Join(",", NetworkNames.SplitList(t.LocalSubnets));
            var remotes = string.Join(",", NetworkNames.SplitList(t.RemoteSubnets));
            sb.AppendLine($"    {pre}{t.Name} {{  # {t.Description ?? "site-to-site"}{(t.IsEnabled ? "" : " [disabled]")}")
              .AppendLine($"    {pre}    version = {t.IkeVersion}")
              .AppendLine($"    {pre}    remote_addrs = {t.RemoteGateway}")
              .AppendLine($"    {pre}    proposals = {t.Proposals}")
              .AppendLine($"    {pre}    local {{ auth = psk }}")
              .AppendLine($"    {pre}    remote {{ auth = psk }}")
              .AppendLine($"    {pre}    children {{")
              .AppendLine($"    {pre}        {t.Name}-net {{")
              .AppendLine($"    {pre}            local_ts = {locals}")
              .AppendLine($"    {pre}            remote_ts = {remotes}")
              .AppendLine($"    {pre}            esp_proposals = {t.Proposals}")
              .AppendLine($"    {pre}            start_action = trap")
              .AppendLine($"    {pre}            dpd_action = restart")
              .AppendLine($"    {pre}        }}")
              .AppendLine($"    {pre}    }}")
              .AppendLine($"    {pre}}}");
        }
        sb.AppendLine("}").AppendLine().AppendLine("# secrets.conf template (fill in on the device):").AppendLine("# secrets {");
        foreach (var t in tunnels)
            sb.AppendLine($"#     ike-{t.Name} {{ id = {t.RemoteGateway}  secret = \"<pre-shared key>\" }}");
        sb.AppendLine("# }");
        return sb.ToString();
    }

    // ---------------------------------------------------------------- keepalived
    private static string Keepalived(Gateway g, HaCluster cluster, IReadOnlyList<Gateway> members)
    {
        var master = HaCluster.ElectMaster(members);
        var isMaster = master?.Id == g.Id;
        var sb = new StringBuilder().Append(Header(g))
            .AppendLine($"# Cluster '{cluster.Name}': this node is {(isMaster ? "MASTER" : "BACKUP")} (priority {g.HaPriority}).")
            .AppendLine("# For stateful failover of NATed connections also run conntrackd between members.")
            .AppendLine()
            .AppendLine("global_defs {")
            .AppendLine($"    router_id {g.Hostname}")
            .AppendLine("    enable_script_security")
            .AppendLine("}");

        var tracked = g.Interfaces.Where(i => i.IsEnabled && i.Mode != AddressingMode.None).Select(i => i.Name).OrderBy(n => n).ToList();
        var byInterface = cluster.VirtualIps.GroupBy(v => v.Interface).OrderBy(x => x.Key).ToList();

        for (var idx = 0; idx < byInterface.Count; idx++)
        {
            var group = byInterface[idx];
            var iface = group.Key;
            var self = g.Interfaces.FirstOrDefault(i => i.Name == iface)?.AddressCidr;
            var peers = members.Where(m => m.Id != g.Id)
                .Select(m => m.Interfaces.FirstOrDefault(i => i.Name == iface)?.AddressCidr)
                .Where(c => c is not null).Select(c => c!.Value.Address.ToString()).ToList();
            var instance = $"SM_{Sanitize(cluster.Name)}_{Sanitize(iface)}";

            sb.AppendLine()
              .AppendLine($"vrrp_instance {instance} {{")
              // With nopreempt keepalived requires every node to start as BACKUP.
              .AppendLine($"    state {(isMaster && cluster.Preempt ? "MASTER" : "BACKUP")}")
              .AppendLine($"    interface {iface}")
              .AppendLine($"    virtual_router_id {cluster.VrrpRouterId + idx}")
              .AppendLine($"    priority {g.HaPriority}")
              .AppendLine($"    advert_int {cluster.AdvertIntervalSeconds}");
            if (!cluster.Preempt) sb.AppendLine("    nopreempt");
            if (self is { } s) sb.AppendLine($"    unicast_src_ip {s.Address}");
            if (peers.Count > 0)
            {
                sb.AppendLine("    unicast_peer {");
                foreach (var p in peers) sb.AppendLine($"        {p}");
                sb.AppendLine("    }");
            }
            sb.AppendLine("    virtual_ipaddress {");
            foreach (var vip in group.OrderBy(v => v.Address))
                sb.AppendLine($"        {vip.Address} dev {iface}{(vip.Description is null ? "" : $"  # {vip.Description}")}");
            sb.AppendLine("    }");
            if (tracked.Count > 0)
            {
                sb.AppendLine("    track_interface {");
                foreach (var t in tracked) sb.AppendLine($"        {t}");
                sb.AppendLine("    }");
            }
            sb.AppendLine("}");
        }
        return sb.ToString();
    }

    private static string Sanitize(string s) => new(s.Select(c => char.IsLetterOrDigit(c) ? char.ToUpperInvariant(c) : '_').ToArray());

    // ---------------------------------------------------------------- README
    private static string Readme(Gateway g, IReadOnlyList<GeneratedFile> files)
    {
        var sb = new StringBuilder().Append(Header(g)).AppendLine()
            .AppendLine("Files:");
        foreach (var f in files) sb.AppendLine($"  {f.Path,-45} {f.Description}");
        sb.AppendLine()
          .AppendLine("Apply (as root, in this order):")
          .AppendLine("  1. bash network/apply-network.sh")
          .AppendLine("  2. nft -f nftables/sm-nat.nft            (include from /etc/nftables.conf to persist)")
          .AppendLine("  3. WireGuard: copy wireguard/*.conf to /etc/wireguard/, create the key, then: systemctl enable --now wg-quick@<if>")
          .AppendLine("  4. IPsec: copy strongswan/swanctl.d/* to /etc/swanctl/conf.d/, add secrets, then: swanctl --load-all")
          .AppendLine("  5. HA: copy keepalived/keepalived.conf to /etc/keepalived/, then: systemctl restart keepalived")
          .AppendLine()
          .AppendLine("After applying, mark the revision as deployed in Security Manager.");
        return sb.ToString();
    }
}
