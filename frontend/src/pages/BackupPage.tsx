import { useRef, useState } from 'react';
import { useQueryClient } from '@tanstack/react-query';
import { DatabaseBackup, Download, FileJson, Upload } from 'lucide-react';
import { toast } from 'sonner';
import { backupApi, errorMessage } from '../lib/api';
import type { ConfigRestoreResult } from '../lib/types';
import { Card, CardBody, CardHeader, PageHeader } from '../components/ui/Card';
import { Button } from '../components/ui/Button';
import { Switch } from '../components/ui/Form';
import { ConfirmDialog } from '../components/ui/Modal';

interface LoadedBackup {
  fileName: string;
  data: { version?: number; exportedAt?: string; exportedBy?: string; policies?: { rules?: unknown[] }[]; ipList?: unknown[]; feeds?: unknown[] };
}

/** Export the firewall configuration to a JSON file and restore it later or on another installation. */
export default function BackupPage() {
  const queryClient = useQueryClient();
  const fileInput = useRef<HTMLInputElement>(null);
  const [exporting, setExporting] = useState(false);
  const [loaded, setLoaded] = useState<LoadedBackup | null>(null);
  const [replace, setReplace] = useState(false);
  const [confirming, setConfirming] = useState(false);
  const [restoring, setRestoring] = useState(false);
  const [result, setResult] = useState<ConfigRestoreResult | null>(null);

  const doExport = async () => {
    setExporting(true);
    try {
      await backupApi.exportConfig();
      toast.success('Configuration exported');
    } catch (e) {
      toast.error(errorMessage(e));
    } finally {
      setExporting(false);
    }
  };

  const onFile = async (file?: File) => {
    if (!file) return;
    try {
      const data = JSON.parse(await file.text());
      if (!Array.isArray(data?.policies)) throw new Error('This is not a Security Manager firewall backup.');
      setLoaded({ fileName: file.name, data });
      setResult(null);
    } catch (e) {
      toast.error(e instanceof Error ? e.message : 'Could not read the file.');
    } finally {
      if (fileInput.current) fileInput.current.value = '';
    }
  };

  const restore = async () => {
    if (!loaded) return;
    setRestoring(true);
    try {
      const r = await backupApi.importConfig(loaded.data, replace);
      setResult(r);
      setLoaded(null);
      setConfirming(false);
      queryClient.invalidateQueries();
      toast.success('Configuration restored');
    } catch (e) {
      toast.error(errorMessage(e));
    } finally {
      setRestoring(false);
    }
  };

  const ruleCount = loaded?.data.policies?.reduce((n, p) => n + (p.rules?.length ?? 0), 0) ?? 0;

  return (
    <>
      <PageHeader title="Backup & Restore" description="Firewall policies, rules, manual IP list entries, threat feeds and enforcement settings in one portable JSON file." />
      <div className="grid grid-2">
        <Card>
          <CardHeader title="Export" subtitle="Download the current firewall configuration." />
          <CardBody>
            <div className="stack">
              <p className="small muted">Traffic history, hit counters and entries generated by feeds or automatic blocks are not included; they rebuild themselves.</p>
              <div><Button variant="primary" icon={<Download size={16} />} loading={exporting} onClick={doExport}>Download backup</Button></div>
            </div>
          </CardBody>
        </Card>

        <Card>
          <CardHeader title="Restore" subtitle="Apply a backup file to this installation." />
          <CardBody>
            <div className="stack">
              <input ref={fileInput} type="file" accept="application/json,.json" hidden onChange={(e) => onFile(e.target.files?.[0])} />
              {!loaded ? (
                <div><Button icon={<Upload size={16} />} onClick={() => fileInput.current?.click()}>Choose backup file…</Button></div>
              ) : (
                <>
                  <div className="backup-file">
                    <FileJson size={20} />
                    <div style={{ minWidth: 0 }}>
                      <div className="cell-title truncate">{loaded.fileName}</div>
                      <div className="cell-sub">
                        {loaded.data.exportedAt ? `Exported ${new Date(loaded.data.exportedAt).toLocaleString()}` : 'Unknown date'}
                        {loaded.data.exportedBy ? ` by ${loaded.data.exportedBy}` : ''}
                      </div>
                      <div className="small" style={{ marginTop: 4 }}>
                        {loaded.data.policies?.length ?? 0} policies · {ruleCount} rules · {loaded.data.ipList?.length ?? 0} IP entries · {loaded.data.feeds?.length ?? 0} feeds
                      </div>
                    </div>
                  </div>
                  <Switch checked={replace} onChange={setReplace} label={replace ? 'Replace current configuration' : 'Merge into current configuration'} />
                  <p className="small muted">
                    {replace
                      ? 'Deletes all current policies, manual IP entries and feeds, then loads the backup.'
                      : 'Policies and feeds with the same name / URL are overwritten; everything else is kept and new items are added.'}
                  </p>
                  <div className="row-wrap">
                    <Button variant={replace ? 'danger' : 'primary'} icon={<DatabaseBackup size={16} />} onClick={() => setConfirming(true)}>Restore</Button>
                    <Button variant="ghost" onClick={() => setLoaded(null)}>Cancel</Button>
                  </div>
                </>
              )}
              {result && (
                <div className="callout callout-success">
                  Restored {result.policies} policies with {result.rules} rules, {result.ipEntries} new IP entries and {result.feeds} feeds
                  {result.replaced ? ' (replaced the previous configuration).' : ' (merged).'} Hosts pick up the change on their next sync.
                </div>
              )}
            </div>
          </CardBody>
        </Card>
      </div>

      <ConfirmDialog open={confirming} title={replace ? 'Replace firewall configuration' : 'Restore backup'}
        message={replace
          ? <>This <b>deletes every current policy, manual IP entry and feed</b> and loads <b>{loaded?.fileName}</b>. Enforced hosts apply the new rules within seconds. Export a backup first if unsure.</>
          : <>Merge <b>{loaded?.fileName}</b> into the current configuration? Enforced hosts apply the change within seconds.</>}
        confirmLabel={replace ? 'Replace' : 'Restore'} loading={restoring} onConfirm={restore} onClose={() => setConfirming(false)} />
    </>
  );
}
